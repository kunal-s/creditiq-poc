"""The shops and establishments registration certificate as a state labour department's online portal prints it,
drawn at the positions measured on a real portal certificate (iText output): A4, the stacked headings in stroked
Times-Bold (green, red, violet), the display-face title, the certifying sentence in Helvetica 11 with the
establishment's name, the date and the registration number set in underlined Times-Bold 14 and the lines
justified, the eight-row particulars table in 0.5 pt cell rules, the registering authority's block, Place and Signed
Date, and the numbered notes in Times-Bold 9. Everything below the sentence flows as the portal's page does: a longer
address or name pushes the rest down.

The template is another state's certificate; the borrower is in Maharashtra, so the state, the Act, the form and rule
numbers, the office codes in the registration number and the designation are Maharashtra's, and the notes (the portal's
own prose, which spoke of that state's annual fee and penalty dates) are paraphrased into notes that hold under the
Maharashtra Act, where registration does not lapse. The verification note names no web address.

Not drawn (CLAUDE.md rule 8): the state emblem above the headings, the guilloche security border and the background
of repeated small lettering. A plain frame stands in for the border (a pale band at its measured extent edged with
thin rules, then the green inner rule); the emblem's place is left empty.

The template's title face (a licensed blackletter) is not installed; Noto Serif Display Bold (SIL OFL) is used,
condensed to the title's measured width.
"""

