BAND, BAND_RULE = "#DFCFDA", "#86899A"
CX = 297.5                       # the headings' centre line
L, RIGHT = 64.9, 530.1           # the sentence's and the table's left and right edges
EDGES = [64.9, 82.13, 254.43, 271.66, 530.1]
