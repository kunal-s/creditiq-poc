class _Cert(TP.Sheet):
    """A Sheet whose text is placed by its baseline (the portal's own coordinates) and can carry the portal's
    character and word spacing (justified lines), its stroked "bold" (text render mode 2) and a horizontal squeeze;
    cells are stroked rectangles, as the portal draws them."""

    def run(self, x, base, s: str, font: str, size: float, colour: str = INK, *, cs: float = 0.0, ws: float = 0.0,
            stroke: float = 0.0, hs: float = 1.0):
        if s:
            self.ops.append(("j", x, base, s, font, size, TP.rgb(colour), cs, ws, stroke, hs))

    def centred(self, base, s: str, font: str, size: float, colour: str, *, stroke: float = 0.0, fit_w=None):
        w = TP.width(s, font, size)
        hs = fit_w / w if fit_w else 1.0
        self.run(CX - w * hs / 2, base, s, font, size, colour, stroke=stroke, hs=hs)

    def box(self, x0, top, x1, bottom, lw: float = 1.0, colour: str = "#000000"):
        for a in ((x0, top, x1, top), (x0, bottom, x1, bottom), (x0, top, x0, bottom), (x1, top, x1, bottom)):
            self.line(*a, lw=lw, colour=colour)

    def cell(self, x0, top, x1, bottom, lw: float = 0.5):
        self.ops.append(("r", x0, top, x1, bottom, lw))

    def render(self) -> bytes:
        buf = io.BytesIO()
        c = canvas.Canvas(buf, pagesize=(self.w, self.h), invariant=1)
        c.setTitle("")
        for ops in self.pages:
            for op in ops:
                kind = op[0]
                if kind == "f":
                    _, x0, t, x1, b, colour = op
                    c.setFillColorRGB(*colour)
                    c.rect(x0, self.h - b, x1 - x0, b - t, stroke=0, fill=1)
                elif kind == "l":
                    _, x0, t, x1, b, lw, colour = op
                    c.setStrokeColorRGB(*colour)
                    c.setLineWidth(lw)
                    c.line(x0, self.h - t, x1, self.h - b)
                elif kind == "r":
                    _, x0, t, x1, b, lw = op
                    c.saveState()
                    c.setLineCap(2)
                    c.setStrokeColorRGB(0, 0, 0)
                    c.setLineWidth(lw)
                    c.rect(x0, self.h - b, x1 - x0, b - t, stroke=1, fill=0)
                    c.restoreState()
                elif kind == "j":
                    _, x, base, s, font, size, colour, cs, ws, stroke, hs = op
                    c.saveState()
                    c.setFillColorRGB(*colour)
                    c.setStrokeColorRGB(*colour)
                    if stroke:
                        c.setLineWidth(stroke)
                    c.setFont(font, size)
                    c.translate(x, self.h - base)
                    if hs != 1.0:
                        c.scale(hs, 1)
                    c.drawString(0, 0, s, mode=2 if stroke else None, charSpace=cs, wordSpace=ws or None)
                    c.restoreState()
                else:
                    raise ValueError(f"unknown drawing operation {kind!r}")
            c.setFillColorRGB(0, 0, 0)
            c.setFont("Helvetica", 6.5)
            c.drawString(self.footer_x, self.footer_y, D.FOOTER)
            c.showPage()
        c.save()
        return buf.getvalue()


def _frame(s: _Cert):
    """The plain frame standing in for the guilloche border: a pale band at the border's measured extent with a
    double rule along its outer edge and a single rule along its inner edge, then the green inner rule."""
    ox0, otop, ox1, obot = 28.5, 23.0, 580.5, 816.0           # the border's outer extent
    ix0, itop, ix1, ibot = 51.5, 47.6, 556.0, 794.2           # the band's inner edge, just outside the green rule
    for a in ((ox0, otop, ox1, itop), (ox0, ibot, ox1, obot), (ox0, itop, ix0, ibot), (ix1, itop, ox1, ibot)):
        s.fill(*a, BAND)
    for x0, t, x1, b, lw in ((ox0, otop, ox1, obot, 1.0), (ox0 + 5, otop + 5, ox1 - 5, obot - 5, 0.75),
                             (ix0, itop, ix1, ibot, 0.75)):
        s.box(x0, t, x1, b, lw, BAND_RULE)
    s.box(53.3, 49.1, 554.25, 792.6, 1.6, FRAME_GREEN)


def _sentence(s: _Cert, base: float, chunks: list[tuple[str, str, float, bool]], *, lead: float = 20.0) -> float:
    """The certifying sentence: chunks of (text, font, size, underlined) broken at spaces into lines of the measure
    and justified as iText does (character spacing, word spacing 2.5 times it): the last line too when it is nearly
    full, and no line whose letters would spread more than a point apart (one left short by an unbreakable number).
    Underlined chunks get the portal's rule (size/15 thick, size/3 below the baseline). Returns the baseline of the
    last line."""
    chars = [(ch, k) for k, (t, _, _, _) in enumerate(chunks) for ch in t]

    def w(cs):
        return sum(TP.width(ch, chunks[k][1], chunks[k][2]) for ch, k in cs)

    units, cur = [], []
    for item in chars:
        cur.append(item)
        if item[0] == " ":
            units.append(cur)
            cur = []
    if cur:
        units.append(cur)
    measure = RIGHT - L
    lines, line = [], []
    for u in units:
        trial = line + u
        if line and w(_trim(trial)) > measure:
            lines.append(_trim(line))
            line = list(u)
        else:
            line = trial
    lines.append(_trim(line))
    for n, ln in enumerate(lines):
        natural = w(ln)
        spread = (measure - natural) / (sum(ch == " " for ch, _ in ln) * 2.5 + len(ln) - 1)
        full = n < len(lines) - 1 or natural >= 0.9 * measure
        cs = spread if full and spread <= 1.0 else 0.0
        ws = 2.5 * cs
        x = L
        i = 0
        while i < len(ln):
            k = ln[i][1]
            j = i
            while j < len(ln) and ln[j][1] == k:
                j += 1
            text = "".join(ch for ch, _ in ln[i:j])
            _, font, size, under = chunks[k]
            span = TP.width(text, font, size) + cs * len(text) + ws * text.count(" ")
            s.run(x, base, text, font, size, INK, cs=cs, ws=ws)
            if under:
                s.line(x + 0.1, base + size / 3, x + span + 0.1, base + size / 3, lw=size / 15, colour=INK)
            x += span
            i = j
        if n < len(lines) - 1:
            base += lead
    return base


def _trim(cs: list) -> list:
    while cs and cs[-1][0] == " ":
        cs = cs[:-1]
    return cs


def _wrap(text: str, font: str, size: float, room: float) -> list[str]:
    out, cur = [], ""
    for word in text.split(" "):
        trial = f"{cur} {word}" if cur else word
        if cur and TP.width(trial, font, size) > room:
            out.append(cur)
            cur = word
        else:
            cur = trial
    return out + [cur]


def _age(dob: str, on: str, parse) -> int:
    """Completed years on the date `on`."""
    d0, m0, y0 = parse(dob)
    d1, m1, y1 = parse(on)
    return y1 - y0 - ((m1, d1) < (m0, d0))


def shop_establishment_certificate(e: D.Entity | None = None) -> bytes:
    """The registration certificate under the Maharashtra shops and establishments Act for the borrower's premises:
    the employer is the first of e.persons (the managing director, or the proprietor of a proprietorship), the
    address e.office, the date of commencement the date the business began, the registration number made with num()."""
    import realistic_docs as R

    e = e or D.BASE
    who = e.name.upper()
    owner = e.persons[0]
    relative = R.FAMILY.get(owner.name, ("", "-"))[1].split(" (")[0].upper()
    city = e.office.split(", ")[-2].rstrip("0123456789 ")
    place = R.DISTRICT.get(city, city).upper()
    regd = R.dmy(ISSUED)
    reg_no = f"SEA/{place[:3]}/FAC/{CIRCLE[:2]}/{R.num(who, 'shops-establishments')}/{R.parse_date(ISSUED)[2]}"

    s = _Cert(595.0, 842.0, footer_x=28.5, footer_y=14.0)
    _frame(s)
    # the emblem (257.5 to 337.5 across, 72 to 152 down) is not drawn
    s.centred(169.0, "GOVERNMENT OF MAHARASHTRA", TB, 15, GREEN, stroke=0.5)
    s.centred(185.0, "LABOUR DEPARTMENT", TB, 12, RED, stroke=0.4)
    s.centred(200.0, "(See Rule 5)", TB, 11, VIOLET, stroke=11 / 30)
    s.centred(215.0, "FORM - B", TB, 11, VIOLET, stroke=11 / 30)
    s.centred(243.0, "Certificate Of Registration", TITLE_FONT, 24, GOLD, fit_w=254.42)
    s.centred(274.0, f"Reg. No. {reg_no}", TB, 11, PLUM, stroke=11 / 30)
    last = _sentence(s, 298.0, [("It is hereby certified that the ", HV, 11, False), (who, TB, 14, True),
                                (f" has been Registered as Others under the {ACT} on ", HV, 11, False),
                                (regd, TB, 14, True), (" with registration number ", HV, 11, False),
                                (reg_no, TB, 14, True)])

    rows = [("Name of the Employer", owner.name.upper()), ("Father/Husband's Name", relative),
            ("Age of Employer", str(_age(owner.dob, ISSUED, R.parse_date))), ("Name of Shop /Establishment", who),
            ("Shop / Establishment Address", f"{who},{e.office.upper()}"), ("Number of Employees", str(EMPLOYEES)),
            ("Nature of Business", NATURE), ("Date of Commencement", R.dmy(e.incorporated))]
    top = last + 24.0
    for n, (label, value) in enumerate(rows, 1):
        lines = _wrap(value, TB, 11, EDGES[4] - EDGES[3] - 10)
        bottom = top + 10 + 11 * len(lines)
        for x0, x1 in zip(EDGES, EDGES[1:]):
            s.cell(x0, top, x1, bottom)
        s.run(EDGES[0] + 5, top + 16, str(n), TR, 11)
        s.run(EDGES[1] + 5, top + 16, label, TR, 11)
        s.run(EDGES[2] + 5, top + 16, ":", TR, 11)
        for k, ln in enumerate(lines):
            s.run(EDGES[3] + 5, top + 16 + 11 * k, ln, TB, 11)
        top = bottom

    b = top
    s.run(299.5, b + 15, "Registering Authority", TB, 11)
    s.run(299.5, b + 30, f"Name: {OFFICER}", TR, 11)
    s.run(L, b + 45, f"Place: {place}", TR, 11)
    s.run(299.5, b + 45, f"Designation: FACILITATOR_{CIRCLE}", TR, 11)
    s.run(L, b + 60, f"Signed Date: {regd}", TR, 11)
    s.run(67.9, b + 76, "Note:", TB, 9, PLUM)
    base = b + 92
    for n, note in enumerate(NOTES, 1):
        s.run(68.9, base, f"{n}.", TB, 9, PLUM)
        for k, ln in enumerate(_wrap(note, TB, 9, RIGHT - 86.13)):
            s.run(86.13, base + 9 * k, ln, TB, 9, PLUM)
        base += 9 * k + 17
    return s.render()
